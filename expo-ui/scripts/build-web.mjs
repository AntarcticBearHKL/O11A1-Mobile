import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const project = path.resolve(here, '..');
const webDir = path.resolve(project, '..', 'web-prototype');
const outFile = path.resolve(project, 'src', 'webapp.generated.ts');
const names = ['index.html', 'app.js', 'native.js', 'styles.css', 'vendor/hls.min.js'];

const files = {};
for (const name of names) {
  const file = path.join(webDir, name);
  if (!fs.existsSync(file)) {
    console.error(`[build-web] missing ${file}`);
    process.exit(1);
  }
  files[name] = fs.readFileSync(file, 'utf8');
}

const json = JSON.stringify(files)
  .replace(/\u2028/g, '\\u2028')
  .replace(/\u2029/g, '\\u2029');
const buildId = Date.now().toString(36);

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(
  outFile,
  `// Generated by scripts/build-web.mjs from ../../web-prototype. Do not edit.\nexport const WEBAPP_BUILD = ${JSON.stringify(buildId)};\nexport const WEBAPP_FILES: Record<string, string> = ${json};\n`,
  'utf8',
);

const total = Object.values(files).reduce((sum, value) => sum + value.length, 0);
console.log(`[build-web] wrote ${outFile} (${total} chars)`);
